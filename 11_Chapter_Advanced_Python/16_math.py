"""
built-in math functions
The math module provides a set of functions for performing mathematical operations.
Some of the commonly used functions in the math module include:
math.sqrt(x): Returns the square root of x.
math.min(a, b, ...): Returns the smallest of the given arguments.
math.max(a, b, ...): Returns the largest of the given arguments.
math.pow(x, y): Returns x raised to the power of y.
math.ceil(x): Returns the smallest integer greater than or equal to x.
math.floor(x): Returns the largest integer less than or equal to x.
math.factorial(n): Returns the factorial of n.
"""

a = [2, 3, 4, 5]

minimum = min(a)
print(minimum)
maximum = max(a)
print(maximum)
power = pow(2, 3)
print(power)